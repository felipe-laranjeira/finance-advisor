create table if not exists public.ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  feature text not null,
  created_at timestamptz not null default now()
);

create index if not exists ai_usage_user_created_at_idx
  on public.ai_usage (user_id, created_at desc);

create index if not exists ai_usage_created_at_idx
  on public.ai_usage (created_at desc);

alter table public.ai_usage enable row level security;

drop policy if exists "Users can read their own AI usage" on public.ai_usage;
create policy "Users can read their own AI usage"
  on public.ai_usage
  for select
  to authenticated
  using (user_id = (select auth.uid()));

revoke all on public.ai_usage from anon, authenticated;
grant select on public.ai_usage to authenticated;

create or replace function public.consume_ai_usage(
  p_user_id uuid,
  p_feature text,
  p_user_hourly_limit integer,
  p_user_daily_limit integer,
  p_global_daily_limit integer
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  request_time timestamptz := now();
  user_hourly_count integer;
  user_daily_count integer;
  global_daily_count integer;
begin
  if auth.role() is distinct from 'service_role'
    or p_user_id is null
    or p_feature is null
    or p_feature not in (
      'expense-import',
      'income-import',
      'investment-import',
      'subscription-analysis',
      'budget-review',
      'investment-advisor'
    )
    or p_user_hourly_limit < 1
    or p_user_daily_limit < 1
    or p_global_daily_limit < 1
  then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtextextended('ai_usage:global', 0));

  delete from public.ai_usage
  where created_at < request_time - interval '24 hours';

  select count(*) into user_hourly_count
  from public.ai_usage
  where user_id = p_user_id
    and created_at >= request_time - interval '1 hour';

  select count(*) into user_daily_count
  from public.ai_usage
  where user_id = p_user_id
    and created_at >= request_time - interval '24 hours';

  select count(*) into global_daily_count
  from public.ai_usage
  where created_at >= request_time - interval '24 hours';

  if user_hourly_count >= p_user_hourly_limit
    or user_daily_count >= p_user_daily_limit
    or global_daily_count >= p_global_daily_limit
  then
    return false;
  end if;

  insert into public.ai_usage (user_id, feature)
  values (p_user_id, p_feature);

  return true;
end;
$$;

revoke all on function public.consume_ai_usage(uuid, text, integer, integer, integer)
  from public, anon, authenticated;
grant execute on function public.consume_ai_usage(uuid, text, integer, integer, integer)
  to service_role;
